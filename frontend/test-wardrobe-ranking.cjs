const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const nodes = Object.fromEntries(['#load-wardrobe-matches','#wardrobe-match-status','#wardrobe-matches','#match-category','#match-strength'].map(id=>[id, {}]));
const events = {};
let resolve, requestedPath;
const context = vm.createContext({document:{querySelector:id=>nodes[id]},window:{addEventListener:(name,fn)=>events[name]=fn},mode:'demo',api:path=>{requestedPath=path;return new Promise(r=>resolve=r)},esc:s=>s.replaceAll('<','&lt;')});
vm.runInContext(fs.readFileSync(__dirname+'/wardrobe-ranking.js','utf8'),context);
(async()=>{
 const button=nodes['#load-wardrobe-matches'], results=nodes['#wardrobe-matches'], status=nodes['#wardrobe-match-status'];
 assert.equal(button.disabled,true);
 context.mode='live';events['wardrobe-context']();
 let request=button.onclick();
 resolve({items:[{item_name:'<Top>',score:2,reasons:['Palette match']}]});await request;
 assert.match(results.innerHTML,/&lt;Top>/);
 assert.match(results.innerHTML,/2 \/ 3/);
 request=button.onclick();events['wardrobe-context']();resolve({items:[{item_name:'Stale',score:0,reasons:[]}]});await request;
 assert.equal(results.innerHTML,'');
 request=button.onclick();resolve({items:[]});await request;
 assert.match(status.textContent,/Add a piece/);
 nodes['#match-category'].value='Tops';nodes['#match-category'].onchange();
 request=button.onclick();assert.equal(requestedPath,'wardrobe-ranking?limit=5&include_coverage=true&min_score=0&category=Tops');
 nodes['#match-category'].value='Bottoms';nodes['#match-category'].onchange();resolve({items:[{item_name:'Old top',score:1,reasons:[]}]});await request;assert.equal(results.innerHTML,'');
 request=button.onclick();resolve({items:[]});await request;assert.match(status.textContent,/No pieces in this category/);
 nodes['#match-strength'].value='3';nodes['#match-strength'].onchange();
 request=button.onclick();assert.equal(requestedPath,'wardrobe-ranking?limit=5&include_coverage=true&min_score=3&category=Bottoms');
 resolve({items:[]});await request;assert.match(status.textContent,/No pieces meet these filters/);
 request=button.onclick();nodes['#match-strength'].value='0';nodes['#match-strength'].onchange();
 resolve({items:[{item_name:'Old strict result',score:3,reasons:[]}]});await request;assert.equal(results.innerHTML,'');
 request=button.onclick();
 resolve({items:[{item_name:'Jeans',score:1,reasons:['Style match']}],coverage:{candidate_count:12,matching_item_count:7,eligible_count:12}});await request;
 assert.match(status.textContent,/7 of 12 pieces in this category/);
 assert.match(status.textContent,/12 pass your match-strength filter; showing 1/);
 nodes['#match-category'].value='';nodes['#match-category'].onchange();
 assert.doesNotMatch(status.textContent,/7 of 12/);
 nodes['#match-strength'].value='3';
 request=button.onclick();
 resolve({items:[],coverage:{candidate_count:4,matching_item_count:2,eligible_count:0}});await request;
 assert.match(status.textContent,/2 of 4 pieces in your wardrobe/);
 assert.match(status.textContent,/0 pass your match-strength filter; showing 0/);
 assert.match(status.textContent,/No pieces meet these filters/);
 request=button.onclick();
 resolve({items:[],coverage:{candidate_count:0,matching_item_count:0,eligible_count:0}});await request;
 assert.doesNotMatch(status.textContent,/0 of 0|NaN/);
 context.api=async()=>{throw new Error('Offline')};await button.onclick();
 assert.match(status.textContent,/Try again/);assert.equal(button.disabled,false);
 console.log('Wardrobe match rendering, empty/error, demo, and stale-response checks passed.');
})().catch(error=>{console.error(error);process.exitCode=1});
